"""PyTorch Geometric (PyG) dataset wrapper for elastic mesh data.

This module provides a standard PyG InMemoryDataset interface for loading
and using the elastic spring network datasets generated by generate_dataset.py.

PyG's InMemoryDataset class handles:
  - Automatic caching: processed data is saved to disk on first load.
  - Batching: PyG's DataLoader can collate variable-size graphs into batches.
  - Transforms: optional transforms can be applied on-the-fly.

The dataset can be initialized in two ways:
  1. From pre-generated .pt files (the normal workflow after running generate_dataset.py)
  2. On-the-fly generation (for quick tests — generates a small default set)

Typical workflow:
    # Step 1: Generate data (run once, saves .pt files)
    python generate_dataset.py --output_dir ./data/processed --n_train 1000

    # Step 2: Load as a PyG dataset
    from data.dataset import ElasticMeshDataset
    train_set = ElasticMeshDataset(root='./data', split='train')
    loader = DataLoader(train_set, batch_size=64, shuffle=True)
"""

import torch
from pathlib import Path

try:
    from torch_geometric.data import InMemoryDataset, Data
except ImportError:
    raise ImportError("torch_geometric is required. Install with: "
                      "pip install torch-geometric")


class ElasticMeshDataset(InMemoryDataset):
    """PyG dataset of elastic spring network graphs with elastic property labels.

    Each sample is a graph where:
      - Nodes represent mesh vertices (with position and local statistics)
      - Edges represent springs (with rigidity, rest length, and type flag)
      - Labels are the elastic properties (Poisson's ratio, Young's modulus, tensor)

    The dataset inherits from PyG's InMemoryDataset, which loads all data into
    memory for fast access during training. For the typical dataset sizes we use
    (80k-100k graphs with ~500 nodes each), this requires ~2-4 GB of RAM.

    Usage:
        # From pre-generated .pt files:
        dataset = ElasticMeshDataset(root='./data', split='train')

        # Generate on-the-fly (small test set):
        dataset = ElasticMeshDataset(root='./data', split='test')  # auto-generates if missing

        # Generate and save programmatically:
        dataset = ElasticMeshDataset.generate_and_save(
            root='./data', split='train', n_samples=1000
        )
    """

    def __init__(self, root, split='train', transform=None, pre_transform=None):
        self.split = split
        # super().__init__ triggers process() if processed file doesn't exist
        super().__init__(root, transform, pre_transform)
        # self.load() reads the collated data from the processed .pt file
        self.load(self.processed_paths[0])

    @property
    def raw_file_names(self):
        # No raw files needed — data is either pre-processed or generated on-the-fly
        return []

    @property
    def processed_file_names(self):
        # One file per split: train.pt, val.pt, or test.pt
        return [f'{self.split}.pt']

    def process(self):
        """Called by PyG when the processed file doesn't exist.

        First checks for a pre-generated .pt file in the raw/ directory.
        If not found, falls back to generating a small default dataset
        (useful for testing the pipeline without a full data generation run).
        """
        raw_path = Path(self.root) / 'raw' / f'{self.split}.pt'
        if raw_path.exists():
            data_list = torch.load(raw_path, weights_only=False)
            self.save(data_list, self.processed_paths[0])
        else:
            # Fallback: generate a small dataset for quick testing.
            # In production, always pre-generate via generate_dataset.py CLI.
            from data.generate_dataset import generate_dataset
            print(f"No pre-generated data found. Generating small {self.split} set...")
            n = {'train': 500, 'val': 100, 'test': 100}.get(self.split, 100)
            data_list = generate_dataset(n)
            self.save(data_list, self.processed_paths[0])

    @classmethod
    def generate_and_save(cls, root, split='train', n_samples=1000,
                          n_workers=1, **kwargs):
        """Generate a dataset and save it in PyG's expected format.

        This is a convenience method that combines data generation and saving
        into one step. After calling this, the dataset can be loaded with
        the normal constructor.

        Args:
            root: dataset root directory. Data is saved to root/processed/{split}.pt.
            split: 'train', 'val', or 'test'.
            n_samples: number of samples to generate.
            n_workers: parallel workers for generation.
            **kwargs: additional arguments passed to generate_dataset().

        Returns:
            ElasticMeshDataset instance (ready to use).
        """
        from data.generate_dataset import generate_dataset

        root = Path(root)
        processed_dir = root / 'processed'
        processed_dir.mkdir(parents=True, exist_ok=True)

        data_list = generate_dataset(n_samples, n_workers=n_workers, **kwargs)

        save_path = processed_dir / f'{split}.pt'
        from torch_geometric.data import InMemoryDataset as _IMS
        # Use PyG's collate protocol to efficiently store the data list
        torch.save(
            _IMS.collate(data_list),
            save_path,
        )
        print(f"Saved {len(data_list)} samples to {save_path}")

        return cls(root, split)
